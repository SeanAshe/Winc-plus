/// 返回环境 `name` 开头要跳过的参数个数。
pub(super) fn env_args(name: &str) -> usize {
    match name {
        "minipage" | "subfigure" | "subtable" | "multicols" | "multicols*" | "adjustbox"
        | "column" | "spacing" => 1,
        "wrapfigure" | "wraptable" => 2,
        _ => 0,
    }
}
